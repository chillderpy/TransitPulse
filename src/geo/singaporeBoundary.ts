// Fast first check: anything outside this box cannot be in Singapore.
const SG_BBOX = { latMin: 1.216, latMax: 1.471, lonMin: 103.606, lonMax: 104.035 };

/** Ray-casting point-in-polygon test. */
function inPolygon(lat: number, lon: number, poly: ReadonlyArray<LatLon>): boolean {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [latI, lonI] = poly[i];
    const [latJ, lonJ] = poly[j];
    if (latI > lat !== latJ > lat) {
      const lonCross = lonI + ((lat - latI) * (lonJ - lonI)) / (latJ - latI);
      if (lon < lonCross) inside = !inside;
    }
  }
  return inside;
}

/** True if the WGS84 point lies within (the approximate outline of) Singapore. */
export function isInSingapore(lat: number, lon: number): boolean {
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) return false;
  if (lat < SG_BBOX.latMin || lat > SG_BBOX.latMax || lon < SG_BBOX.lonMin || lon > SG_BBOX.lonMax) {
    return false;
  }
  return SG_POLYGONS.some((p) => inPolygon(lat, lon, p.points));
}
